export function getWordById(id: string): VocabularyItem | undefined {
  return vocabulary.find((w) => w.id === id);
}

export function searchVocabulary(query: string): VocabularyItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return vocabulary.filter(
    (w) =>
      w.hanzi.includes(query) ||
      w.pinyin.toLowerCase().includes(q) ||
      w.meaning.toLowerCase().includes(q)
  );
}

export function getVocabularyByHsk(level: number): VocabularyItem[] {
  return vocabulary.filter((w) => w.hsk === level);
}
